"""
Kite API Adapter - Uses official Kite Connect API with shared token from SNAIL

This adapter reads the access token generated by SNAIL bot at 8:45 AM daily
and uses the official kiteconnect library for all API operations.

Benefits over enctoken:
- Official API (more stable, no web scraping)
- No credentials needed in CROCODILE (SNAIL handles auth)
- Better error messages and documentation
- Rate limiting handled by library
"""

import json
import os
import time
from datetime import datetime, timedelta
from typing import Dict, Any, List, Optional

import pandas as pd
from loguru import logger

from src.api.broker_adapter import BrokerAdapter
from src.core.api_resilience import critical_api_call, standard_api_call
from src.utils.timezone_helper import now_ist, today_ist, IST

# Try to import kiteconnect
try:
    from kiteconnect import KiteConnect
    KITECONNECT_AVAILABLE = True
except ImportError:
    KITECONNECT_AVAILABLE = False
    logger.warning("kiteconnect library not installed. Run: pip install kiteconnect")


class KiteAPIAdapter(BrokerAdapter):
    """
    Kite API adapter using official kiteconnect library

    Reads access token from shared file created by SNAIL bot.
    """

    def __init__(self, config: Dict[str, Any]):
        """
        Initialize Kite API adapter

        Args:
            config: Configuration dictionary (already loaded)
        """
        if not KITECONNECT_AVAILABLE:
            raise ImportError(
                "kiteconnect library required for Kite API mode. "
                "Install with: pip install kiteconnect"
            )

        self.config = config
        self._kite: Optional[KiteConnect] = None
        self._api_key: Optional[str] = None
        self._user_id: Optional[str] = None
        self._order_tag = config.get('kite', {}).get('order_tag', 'croc')
        self._rate_limit_delay = config.get('kite', {}).get('rate_limit_delay', 1.0)

        # Token file path (from SNAIL)
        kite_api_config = config.get('kite', {}).get('kite_api', {})
        self._token_file = kite_api_config.get('token_file', '../data/kite_access_token.json')
        self._validate_token_date = kite_api_config.get('validate_token_date', True)

        # Resolve relative path
        if not os.path.isabs(self._token_file):
            project_root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
            self._token_file = os.path.normpath(os.path.join(project_root, self._token_file))

        # Data cache
        self._cache = {}
        self._instruments_cache = {}
        self.instruments_file = config.get('instruments', {}).get('cache_file', 'data/instruments.csv')

        # Resolve instruments file path
        if not os.path.isabs(self.instruments_file):
            project_root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
            self.instruments_file = os.path.normpath(os.path.join(project_root, self.instruments_file))

        logger.info(f"KiteAPIAdapter initialized (token file: {self._token_file})")

    def _load_token(self) -> Dict[str, Any]:
        """
        Load access token from shared JSON file

        Returns:
            Dict with access_token, api_key, user_id, generated_at

        Raises:
            FileNotFoundError: If token file doesn't exist
            ValueError: If token is expired or invalid
        """
        if not os.path.exists(self._token_file):
            raise FileNotFoundError(
                f"Kite API token file not found: {self._token_file}\n"
                "Ensure SNAIL bot has run morning startup to generate token."
            )

        with open(self._token_file, 'r') as f:
            token_data = json.load(f)

        # Validate token date if enabled
        if self._validate_token_date:
            generated_at = token_data.get('generated_at', '')
            if generated_at:
                try:
                    # Parse ISO format datetime
                    token_time = datetime.fromisoformat(generated_at.replace('Z', '+00:00'))

                    # Make timezone-aware if not already
                    if token_time.tzinfo is None:
                        token_time = token_time.replace(tzinfo=IST)

                    current_time = now_ist()

                    # Token is valid if generated today OR yesterday after 6 AM and before today 6 AM
                    today_6am = current_time.replace(hour=6, minute=0, second=0, microsecond=0)

                    if current_time < today_6am:
                        # Before 6 AM today - token from yesterday is valid
                        valid_from = (today_6am - timedelta(days=1))
                    else:
                        # After 6 AM today - token must be from today
                        valid_from = today_6am

                    if token_time < valid_from:
                        raise ValueError(
                            f"Kite API token expired. Generated at {generated_at}, "
                            f"but must be generated after {valid_from.isoformat()}. "
                            "Ensure SNAIL morning startup has run today."
                        )

                    logger.debug(f"Token validated: generated at {generated_at}")

                except (ValueError, TypeError) as e:
                    if "Kite API token expired" in str(e):
                        raise
                    logger.warning(f"Could not validate token date: {e}")

        return token_data

    def _get_kite(self) -> KiteConnect:
        """
        Get authenticated KiteConnect instance

        Returns:
            Authenticated KiteConnect instance
        """
        if self._kite is None:
            token_data = self._load_token()

            self._api_key = token_data.get('api_key')
            self._user_id = token_data.get('user_id')
            access_token = token_data.get('access_token')

            if not all([self._api_key, access_token]):
                raise ValueError(
                    "Invalid token file format. Expected: api_key, access_token"
                )

            self._kite = KiteConnect(api_key=self._api_key)
            self._kite.set_access_token(access_token)

            logger.info(f"KiteConnect initialized for user: {self._user_id}")

        return self._kite

    def _rate_limit(self):
        """Apply rate limiting before API calls"""
        time.sleep(self._rate_limit_delay)

    # =========================================================================
    # CONNECTION & VALIDATION
    # =========================================================================

    def validate_connection(self) -> bool:
        """Validate API connection and token"""
        try:
            kite = self._get_kite()
            profile = kite.profile()
            logger.info(f"Connection validated for user: {profile.get('user_id')}")
            return True
        except Exception as e:
            logger.error(f"Connection validation failed: {e}")
            return False

