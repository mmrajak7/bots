    @standard_api_call("Place Order")
    def place_order(
        self,
        tradingsymbol: str,
        exchange: str,
        transaction_type: str,
        quantity: int,
        order_type: str,
        price: Optional[float] = None,
        product: str = "CNC",
        validity: str = "DAY",
        tag: Optional[str] = None
    ) -> Dict[str, Any]:
        """Place order on Zerodha"""
        self._rate_limit()
        kite = self._get_kite()

        order_params = {
            'exchange': exchange,
            'tradingsymbol': tradingsymbol,
            'transaction_type': transaction_type,
            'quantity': quantity,
            'order_type': order_type,
            'product': product,
            'validity': validity,
        }

        if order_type == "LIMIT" and price:
            order_params['price'] = price

        if tag:
            order_params['tag'] = tag
        elif self._order_tag:
            order_params['tag'] = self._order_tag

        order_id = kite.place_order(variety='regular', **order_params)

        logger.info(
            f"Order placed: {transaction_type} {quantity} {tradingsymbol} @ "
            f"{price if price else 'MARKET'} - Order ID: {order_id}"
        )

        return {'order_id': order_id}

    @critical_api_call("Cancel Regular Order")
    def cancel_order(self, order_id: str, variety: str = "regular", verify: bool = True) -> bool:
        """Cancel a regular order"""
        self._rate_limit()
        kite = self._get_kite()

        kite.cancel_order(variety=variety, order_id=order_id)
        logger.info(f"Cancel request sent for order: {order_id}")

        if verify:
            time.sleep(1)
            try:
                order_status = self.get_order_status(order_id)
                actual_status = order_status.get('status', '')

                if actual_status == 'CANCELLED':
                    logger.info(f"Order cancellation verified: {order_id}")
                    return True
                elif actual_status in ['COMPLETE', 'REJECTED']:
                    logger.warning(f"Order {order_id} cannot be cancelled - status is {actual_status}")
                    return False
                else:
                    raise Exception(f"Order cancellation failed. Order {order_id} still {actual_status}")
            except Exception as e:
                if "cancellation failed" in str(e):
                    raise
                logger.warning(f"Could not verify cancellation for {order_id}: {e}")
                return True

        return True

    @standard_api_call("Get Order Status")
    def get_order_status(self, order_id: str) -> Dict[str, Any]:
        """Get status of a specific order"""
        self._rate_limit()
        kite = self._get_kite()

        order_history = kite.order_history(order_id=order_id)

        if not order_history:
            raise Exception(f"No order history found for order_id: {order_id}")

        latest_order = order_history[-1]

        logger.debug(
            f"Order {order_id} status: {latest_order.get('status')}, "
            f"filled: {latest_order.get('filled_quantity', 0)}/{latest_order.get('quantity', 0)}"
        )

        return latest_order

    def get_all_orders(self) -> List[Dict[str, Any]]:
        """Get all orders placed today"""
        try:
            self._rate_limit()
            kite = self._get_kite()
            all_orders = kite.orders()
            logger.info(f"Fetched {len(all_orders)} orders from Zerodha")
            return all_orders
        except Exception as e:
            logger.error(f"Failed to fetch all orders: {e}")
            raise

    def get_bot_orders(self, tag: Optional[str] = None) -> List[Dict[str, Any]]:
        """Get orders placed by this bot (filtered by tag)"""
        try:
            if tag is None:
                tag = self._order_tag

            all_orders = self.get_all_orders()
            bot_orders = [order for order in all_orders if order.get('tag') == tag]

            logger.info(f"Found {len(bot_orders)} bot orders (tag='{tag}')")
            return bot_orders
        except Exception as e:
            logger.error(f"Failed to fetch bot orders: {e}")
            raise

